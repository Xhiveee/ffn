export function mixinsJson(ctx: ProjectContext): string {
  const p = ctx.profile;
  const json: Record<string, unknown> = {
    required: true,
    minVersion: "0.8",
    package: `${ctx.params.package}.mixin`,
    compatibilityLevel: mixinCompatibilityLevel(p),
  };
  if (p.mixin.refmap && p.buildSystem !== "fabric-loom") {
    // Loom injects the refmap entry itself; ForgeGradle/MDG need it declared.
    json.refmap = `${ctx.params.modId}.refmap.json`;
  }
  json.mixins = ["ExampleMixin"];
  json.client = [];
  json.server = [];
  json.injectors = { defaultRequire: 1 };
  json.overwrites = { requireAnnotations: true };
  return `${JSON.stringify(json, null, 2)}\n`;
}

export function exampleMixin(ctx: ProjectContext): string {
  const { params, profile } = ctx;
  const sample = profile.sampleMixin[params.mappings] ?? profile.sampleMixin.mojmap;
  if (!sample) throw new Error(`Profile has no sampleMixin for mappings ${params.mappings}`);
  const simple = sample.targetClass.split(".").at(-1)!;
  const handler = `${params.modId}$on${sample.method[0]!.toUpperCase()}${sample.method.slice(1)}`;
  return `package ${params.package}.mixin;

import ${params.package}.${params.mainClass};
import ${sample.targetClass};
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/**
 * Example mixin generated by FFN for Minecraft ${profile.mcVersion} (${profile.loader}, ${params.mappings} names).
 * ${sample.comment ?? ""}
 *
 * Registered in ${params.modId}.mixins.json; ${registrationNote(ctx)}
 * Prefer a loader event/API when one exists — mixins are the most version-fragile part of a mod.
 */
@Mixin(${simple}.class)
public abstract class ExampleMixin {
    @Inject(method = "${sample.method}", at = @At("HEAD"))
    private void ${handler}(CallbackInfo ci) {
        ${params.mainClass}.LOGGER.info("[{}] ExampleMixin: ${simple}.${sample.method}() called", ${params.mainClass}.MOD_ID);
    }
}
`;
}

function registrationNote(ctx: ProjectContext): string {
  switch (ctx.profile.mixin.registration) {
    case "fabric.mod.json":
      return 'the config is listed under "mixins" in fabric.mod.json.';
    case "mods.toml":
      return `the config is declared with [[mixins]] in ${ctx.profile.metadata.file}.`;
    case "manifest":
      return `the config is listed in the jar manifest (MixinConfigs)${ctx.profile.mixin.devRunArg ? " and passed to dev runs via --mixin.config" : ""}.`;
  }
}

export function langJson(ctx: ProjectContext): string {
  return `${JSON.stringify({ [`${ctx.params.modId}.mod_name`]: ctx.params.modName }, null, 2)}\n`;
}

export function packMcmeta(ctx: ProjectContext): string | null {
  const pm = ctx.profile.packMeta;
  if (pm.kind === "none" || pm.format === undefined) return null;
  const pack: Record<string, unknown> = { description: `${ctx.params.modName} resources` };
  if (pm.kind === "pack_format") pack.pack_format = pm.format;
  else {
    pack.min_format = pm.format;
    pack.max_format = pm.format;
  }
  return `${JSON.stringify({ pack }, null, 2)}\n`;
}

export function projectReadme(ctx: ProjectContext): string {
  const { params, profile, versions } = ctx;
  const lines = [
    `# ${params.modName}`,
    "",
    `Generated by FFN for **${profile.loader} / Minecraft ${versions.minecraft}**.`,
    "",
    "| | |",
    "|---|---|",
    `| Mod ID | \`${params.modId}\` |`,
    `| Loader version | \`${versions.loader}\` |`,
    `| Build system | ${profile.buildSystem} (\`${profile.plugin.id}\` ${versions.pluginVersion}) |`,
    `| Gradle | ${profile.gradle.version} |`,
    `| Java | ${profile.java} |`,
    `| Mappings | ${params.mappings}${versions.parchment ? ` (${versions.parchment})` : ""}${versions.yarn ? ` (${versions.yarn})` : ""} |`,
    "",
    "## Build",
    "",
    "```sh",
    "./gradlew build        # jar in build/libs/",
    "./gradlew runClient    # start a dev client with the mod loaded",
    "```",
    "",
    profile.gradle.minJvm && profile.gradle.minJvm > profile.java
      ? `Gradle must run on JDK ${profile.gradle.minJvm}+ (required by ${profile.plugin.id}); the mod itself is compiled for Java ${profile.java}.`
      : `Requires a JDK ${profile.java} (Gradle's toolchain support can download it automatically).`,
    "",
  ];
  if (profile.warnings.length) {
    lines.push("## Warnings from FFN", "", ...profile.warnings.map((w) => `- ${w}`), "");
  }
  return lines.join("\n");
}

