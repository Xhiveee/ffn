import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { LoaderSchema } from "../profiles/schema.js";
import { portMixins } from "../port/mixinPort.js";
import { PortError, portMod } from "../port/portMod.js";
import type { Services } from "../services.js";
import { fail, guard, ok } from "./result.js";

export const mixinPortInput = {
  projectDir: z.string().describe("Mod project whose mixins should be checked"),
  toMcVersion: z.string().optional().describe("Target Minecraft version (default: the project's)"),
  toLoader: LoaderSchema.optional().describe("Target loader (default: the project's)"),
  apply: z.boolean().optional().describe("Rewrite high-confidence fixes in place (class/member renames in imports, selectors and @Shadow names) and re-validate. Default false (report only)."),
  fromMcVersion: z.string().optional().describe("Version the mixins were written for, when the files were already copied into a target-version project"),
};

export const portModInput = {
  projectDir: z.string().describe("Source mod project (left untouched)"),
  targetDir: z.string().describe("New, empty directory for the ported project"),
  toMcVersion: z.string().optional().describe("Target Minecraft version (default: unchanged)"),
  toLoader: LoaderSchema.optional().describe("Target loader (default: unchanged)"),
  dryRun: z.boolean().optional().describe("Default true: only report the plan (files, renames, content replay, mixin analysis). Pass false to write."),
  compile: z.boolean().optional().describe("After writing, run compileJava on the target and map errors to target classes and docs/primer hits (default true)"),
  docs: z.boolean().optional().describe("Look compile breakages up in docs_search (default true)"),
};

export function registerPortTools(server: McpServer, services: Services): void {
  server.registerTool(
    "mixin_port",
    {
      title: "Port mixins",
      description:
        "Check a project's mixins against another Minecraft version and/or loader and suggest replacements for every broken target (class, method, field) with a confidence level: high = same Fabric intermediary name in both versions or a uniquely moved class; medium = same name with a changed signature, or a single new member with the old descriptor; low = similar names. apply=true rewrites only high-confidence fixes and re-validates against the target version.",
      inputSchema: mixinPortInput,
      annotations: { readOnlyHint: false, destructiveHint: false, openWorldHint: true },
    },
    (a) =>
      guard(async () => {
        const r = await portMixins(services, { projectDir: a.projectDir, toVersion: a.toMcVersion, toLoader: a.toLoader, apply: a.apply, fromVersion: a.fromMcVersion });
        const hi = r.broken.filter((b) => b.suggestions[0]?.confidence === "high").length;
        const summary =
          `${r.mixinFiles.length} mixin file(s) checked against ${r.to.loader} ${r.to.mcVersion}: ${r.broken.length} broken reference(s) (${hi} with a high-confidence fix), ${r.otherErrors.length} other error(s).` +
          (a.apply ? ` Applied ${r.applied.reduce((n, f) => n + f.changes.length, 0)} change(s) in ${r.applied.length} file(s); ${r.remaining?.errors ?? 0} error(s) remain.` : hi ? " Re-run with apply=true to rewrite the high-confidence ones." : "");
        return ok(summary, r);
      }),
  );
  server.registerTool(
    "port_mod",
    {
      title: "Port mod",
      description:
        "Port a mod project to another Minecraft version and/or loader into a NEW directory (the source is never modified; dry run by default). Build files, metadata and the Gradle wrapper come from the target profile; hand-written code and resources are copied (data pack folders renamed for the target); content generated by FFN (.ffn/content.json) is regenerated with the target's templates; mixins are checked and high-confidence fixes applied (mixin_port); then the target is compiled and errors are mapped to target classes and docs/primer pages. Returns what compiled and what needs manual work.",
      inputSchema: portModInput,
      annotations: { readOnlyHint: false, destructiveHint: false, openWorldHint: true },
    },
    (a) =>
      guard(async () => {
        try {
          const r = await portMod(services, a);
          const s = r.dryRun
            ? `Dry run: port ${r.source.loader} ${r.source.mcVersion} → ${r.target.loader} ${r.target.mcVersion} would write ${r.files.length} file(s) to ${r.target.dir}, replay ${r.replay.length} content request(s); ${r.mixins?.broken.length ?? 0} broken mixin reference(s). Pass dryRun=false to write.`
            : `Ported ${r.source.loader} ${r.source.mcVersion} → ${r.target.loader} ${r.target.mcVersion} into ${r.target.dir}: content ${r.replay.filter((x) => x.status === "regenerated").length}/${r.replay.length} regenerated; mixins ${r.mixins?.applied.length ?? 0} file(s) fixed, ${r.mixins?.remaining?.errors ?? "?"} error(s) left; compile ${r.compile ? `${r.compile.status} (${r.compile.errors} error(s))` : "skipped"}. ${r.manual.length} manual step(s). Report saved to .ffn/port/report.json.`;
          return ok(s, r);
        } catch (e) {
          if (e instanceof PortError) return fail(e.message);
          throw e;
        }
      }),
  );
}
